package criacaometodos01;

public class Calc {
    
    public static double somar(int n1, int n2){
        return (n1 + n2);
    }
    public static double subtrair(int n1, int n2){
        return (n1 - n2);
    }
    public static double multiplicar(int n1, int n2){
        return (n1 * n2);
    }
    public static double dividir(int n1, int n2){
        return (n1 / n2);
    }
    
}
